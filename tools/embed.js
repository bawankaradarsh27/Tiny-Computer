// Wraps games/*.asm into src/<name>_asm.js as TC.samples.<name> = `...`
// Usage: node tools/embed.js
var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '..');
var gamesDir = path.join(root, 'games');
fs.readdirSync(gamesDir).filter(function (f) { return /\.asm$/.test(f); }).forEach(function (f) {
  var name = f.replace(/\.asm$/, '');
  var text = fs.readFileSync(path.join(gamesDir, f), 'utf8').replace(/\r\n/g, '\n');
  var esc = text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  var out =
    "var TC = (typeof globalThis.TC !== 'undefined') ? globalThis.TC : {};\n" +
    '// GENERATED by tools/embed.js from games/' + f + ' -- do not edit.\n' +
    'TC.samples = TC.samples || {};\n' +
    'TC.samples.' + name + ' = `' + esc + '`;\n' +
    "if (typeof module !== 'undefined') module.exports = globalThis.TC = TC; else globalThis.TC = TC;\n";
  fs.writeFileSync(path.join(root, 'src', name + '_asm.js'), out);
  console.log('wrote src/' + name + '_asm.js');
});
